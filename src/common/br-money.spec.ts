import { percentOfMoney } from './br-money';

describe('percentOfMoney', () => {
  it.each([
    ['180.00', '11.00', '19.80'],
    ['180.00', '10.50', '18.90'],
    ['180.00', '11.50', '20.70'],
    ['100.00', '0', '0.00'],
    ['0.10', '5.00', '0.01'], // 0,005 -> half-up
    ['0.09', '5.00', '0.00'], // 0,0045
    ['1234.56', '11.50', '141.97'], // 141,9744
    ['-100.00', '10.00', '-10.00'],
  ])('%s × %s%% = %s', (valor, pct, esperado) => {
    expect(percentOfMoney(valor, pct)).toBe(esperado);
  });
});
